def ensure_thread_doc(
    token: str,
    config: dict[str, Any],
    base_url: str,
    record: dict[str, Any],
) -> tuple[str, str]:
    fields = record.get("fields") or {}
    existing_value = fields.get(FIELD_THREAD)
    existing = extract_text(existing_value)
    existing_url = extract_url(existing_value)
    existing_doc_id = doc_id_from_url(existing_url)
    if existing_doc_id:
        return existing_doc_id, existing_url

    domain = extract_text(fields.get(FIELD_DOMAIN)) or record.get("record_id", "thread")
    title = f"{domain} Gmail Communication Thread"
    new_doc_id = create_doc(token, title, config.get("output_folder_token", ""))
    try:
        set_tenant_editable(token, new_doc_id)
    except Exception as exc:
        print(f"warning: could not set doc permission for {new_doc_id}: {exc}", file=sys.stderr)
    url = doc_url(base_url, new_doc_id)
    if existing and not existing_doc_id:
        append_blocks(
            token,
            new_doc_id,
            markdown_to_blocks(f"# Previous Communication Thread Field\n\n{existing}"),
        )
    return new_doc_id, url


