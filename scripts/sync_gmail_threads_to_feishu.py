def fetch_doc_blocks(token: str, doc_id: str) -> list[dict[str, Any]]:
    """Fetch document blocks with rich-text styles so highlights remain visible."""
    if not doc_id:
        return []
    blocks: list[dict[str, Any]] = []
    page_token = ""
    while True:
        params: dict[str, Any] = {"page_size": 500}
        if page_token:
            params["page_token"] = page_token
        data = requests.get(
            f"{FEISHU_BASE}/docx/v1/documents/{doc_id}/blocks",
            headers=feishu_headers(token),
            params=params,
            timeout=30,
        ).json()
        if data.get("code") != 0:
            raise RuntimeError(f"Failed to fetch document blocks {doc_id}: {data}")
        payload = data.get("data") or {}
        blocks.extend(payload.get("items") or [])
        if not payload.get("has_more"):
            break
        page_token = str(payload.get("page_token") or "")
    return blocks


def rich_text_block_runs(block: dict[str, Any]) -> tuple[str, list[tuple[str, bool]]]:
    """Return visible block text plus run-level highlight state."""
    payload = None
    for key in (
        "text",
        "heading1",
        "heading2",
        "heading3",
        "heading4",
        "heading5",
        "heading6",
        "heading7",
        "heading8",
        "heading9",
        "bullet",
        "ordered",
        "quote",
    ):
        if isinstance(block.get(key), dict):
            payload = block[key]
            break
    if not payload:
        return "", []

    runs: list[tuple[str, bool]] = []
    for element in payload.get("elements") or []:
        text_run = element.get("text_run") or {}
        content = str(text_run.get("content") or "")
        style = text_run.get("text_element_style") or {}
        background = style.get("background_color")
        if isinstance(background, (int, float)):
            highlighted = background != 0
        elif background is not None:
            highlighted = str(background).strip().lower() not in {
                "",
                "0",
                "none",
                "null",
                "transparent",
            }
        else:
            highlighted = False
        if content:
            runs.append((content, highlighted))

    # Feishu may store a line break between two highlighted runs without a
    # background color. Preserve that formatting without splitting one human
    # highlight into two fragments.
    normalized_runs = list(runs)
    for index, (content, highlighted) in enumerate(normalized_runs):
        if highlighted or content.strip():
            continue
        previous_highlighted = index > 0 and normalized_runs[index - 1][1]
        next_highlighted = index + 1 < len(normalized_runs) and normalized_runs[index + 1][1]
        if previous_highlighted and next_highlighted:
            normalized_runs[index] = (content, True)

    return "".join(content for content, _ in normalized_runs).strip(), normalized_runs


def rich_text_block(block: dict[str, Any]) -> tuple[str, bool]:
    """Return visible block text and whether any text run has a highlight."""
    text, runs = rich_text_block_runs(block)
    return text, any(highlighted for _, highlighted in runs)


def is_outgoing_email_section(section: str) -> bool:
    """Identify an outgoing section, including manually pasted replies without headers."""
    from_match = re.search(r"(?im)^From:\s*(.+)$", section)
    if from_match:
        return is_our_address(from_match.group(1))
    return bool(
        re.search(
            r"(?ims)(?:^|\n)(?:best|best regards|regards|thanks)\s*[,，]?\s*\n+\s*"
            r"jane(?:\s+jiang)?\b",
            section,
        )
        or re.search(r"(?i)\b[\w.+-]+@(zilliz\.com|milvus\.io)\b", section)
    )


def extract_highlighted_email_sections(blocks: list[dict[str, Any]]) -> list[str]:
    """Extract each contiguous highlighted fragment from outgoing email sections."""
    message_heading = re.compile(r"(?i)^\s*(?:message|sent email)\s+\d+\s*$")
    sections: list[str] = []
    current: list[tuple[str, list[tuple[str, bool]], bool]] = []

    def flush() -> None:
        nonlocal current
        section = "\n".join(text for text, _, _ in current if text).strip()
        if not (section and is_outgoing_email_section(section)):
            current = []
            return

        heading = current[0][0] if current else "Outgoing email"
        from_match = re.search(r"(?im)^From:\s*(.+)$", section)
        source = f"From: {from_match.group(1).strip()}" if from_match else "Direction: outgoing (inferred from signature)"
        highlighted_group: list[str] = []

        def flush_group() -> None:
            nonlocal highlighted_group
            excerpt = "".join(highlighted_group).strip()
            if excerpt:
                sections.append(
                    "\n".join([heading, source, "Highlighted excerpt:", excerpt])
                )
            highlighted_group = []

        for text, runs, is_list in current[1:]:
            if not text:
                flush_group()
                continue

            first_highlight_in_block = True
            for content, highlighted in runs:
                if highlighted:
                    if first_highlight_in_block:
                        if highlighted_group:
                            highlighted_group.append("\n")
                        if is_list:
                            highlighted_group.append("- ")
                        first_highlight_in_block = False
                    highlighted_group.append(content)
                elif content.strip():
                    flush_group()
                    first_highlight_in_block = True
        flush_group()
        current = []

    for block in blocks:
        text, runs = rich_text_block_runs(block)
        block_type = int(block.get("block_type") or 0)
        if message_heading.match(text):
            flush()
            current = [(text, runs, False)]
            continue
        if current and 3 <= block_type <= 11:
            flush()
            continue
        if current:
            is_list = isinstance(block.get("ordered"), dict) or isinstance(block.get("bullet"), dict)
            current.append((text, runs, is_list))
    flush()
    return sections


def visible_doc_text(blocks: list[dict[str, Any]]) -> str:
    """Return document text without changing rich-text styles or block content."""
    return "\n".join(
        text
        for block in blocks
        if (text := rich_text_block(block)[0])
    )


def template_evidence_id(section: str) -> str:
    excerpt = re.split(r"(?i)Highlighted excerpt:\s*", section, maxsplit=1)[-1]
    normalized = re.sub(r"\s+", " ", excerpt).strip().lower()
    return hashlib.sha256(normalized.encode("utf-8")).hexdigest()[:16]


def doc_id_from_url(value: str) -> str:
    match = re.search(r"/docx/([^/?#\s]+)", value or "")
    return match.group(1) if match else ""


def wiki_node_token_from_url(value: str) -> str:
    match = re.search(r"/wiki/([^/?#\s]+)", value or "")
    return match.group(1) if match else ""


def resolve_doc_id_from_value(token: str, value: str) -> str:
    value = (value or "").strip()
    if not value:
        return ""
    doc_id = doc_id_from_url(value)
    if doc_id:
        return doc_id
    wiki_token = wiki_node_token_from_url(value)
    if wiki_token:
        data = requests.get(
            f"{FEISHU_BASE}/wiki/v2/spaces/get_node",
            headers=feishu_headers(token),
            params={"token": wiki_token},
            timeout=20,
        ).json()
        if data.get("code") != 0:
            raise RuntimeError(f"Failed to resolve wiki document {wiki_token}: {data}")
        return str(((data.get("data") or {}).get("node") or {}).get("obj_token") or "")
    return value


