def gmail_service(args: argparse.Namespace):
    Request, Credentials, InstalledAppFlow, WSGITimeoutError, build = import_google_libs()
    token_path = Path(
        args.gmail_token
        or os.environ.get("GMAIL_TOKEN_PATH", "")
        or Path.home() / ".codex" / "gmail_token.json"
    ).expanduser()
    creds = None
    if token_path.exists():
        creds = Credentials.from_authorized_user_file(str(token_path), GMAIL_SCOPES)
    if creds and creds.expired and creds.refresh_token:
        creds.refresh(Request())
    if not creds or not creds.valid:
        credentials_path = Path(
            args.gmail_credentials
            or os.environ.get("GMAIL_OAUTH_CLIENT", "")
            or Path.home() / ".codex" / "gmail_oauth_client.json"
        ).expanduser()
        if not credentials_path.exists():
            raise SystemExit(
                "Missing Gmail OAuth client JSON. Set GMAIL_OAUTH_CLIENT or pass "
                "--gmail-credentials. Create an OAuth desktop client in Google Cloud."
            )
        flow = InstalledAppFlow.from_client_secrets_file(str(credentials_path), GMAIL_SCOPES)
        try:
            creds = flow.run_local_server(
                port=0,
                open_browser=not getattr(args, "no_browser", False),
                timeout_seconds=getattr(args, "auth_timeout_seconds", None),
            )
        except WSGITimeoutError as exc:
            raise SystemExit(
                "Gmail OAuth timed out before the local callback completed. "
                "Re-run auth-gmail with --no-browser, open the printed URL, "
                "and allow the Gmail readonly scope before the timeout expires."
            ) from exc
    token_path.parent.mkdir(parents=True, exist_ok=True)
    token_path.write_text(creds.to_json(), encoding="utf-8")
    os.chmod(token_path, 0o600)
    return build("gmail", "v1", credentials=creds)


def header_map(message: dict[str, Any]) -> dict[str, str]:
    headers = ((message.get("payload") or {}).get("headers") or [])
    return {h.get("name", "").lower(): h.get("value", "") for h in headers}


def decode_body_data(data: str) -> str:
    if not data:
        return ""
    padded = data + "=" * (-len(data) % 4)
    try:
        return base64.urlsafe_b64decode(padded.encode("utf-8")).decode("utf-8", "replace")
    except Exception:
        return ""


class EmailHTMLTextExtractor(HTMLParser):
    """Convert email HTML to text while dropping known quoted-reply containers."""

    QUOTE_CLASSES = {
        "gmail_quote",
        "gmail_attr",
        "yahoo_quoted",
        "protonmail_quote",
        "moz-cite-prefix",
    }
    QUOTE_IDS = {
        "divrplyfwdmsg",
        "appendonsend",
        "mail-editor-reference-message-container",
    }
    BLOCK_TAGS = {"br", "p", "div", "li", "tr", "table", "section", "article"}
    VOID_TAGS = {"br", "hr", "img", "input", "meta", "link", "source", "wbr"}

    def __init__(self) -> None:
        super().__init__(convert_charrefs=True)
        self.parts: list[str] = []
        self.skip_depth = 0

    def handle_starttag(self, tag: str, attrs: list[tuple[str, str | None]]) -> None:
        tag = tag.lower()
        attrs_map = {key.lower(): (value or "") for key, value in attrs}
        classes = set(attrs_map.get("class", "").lower().split())
        element_id = attrs_map.get("id", "").lower()
        quoted = (
            tag in {"blockquote", "script", "style"}
            or bool(classes & self.QUOTE_CLASSES)
            or element_id in self.QUOTE_IDS
        )
        if self.skip_depth:
            if tag not in self.VOID_TAGS:
                self.skip_depth += 1
            return
        if quoted:
            self.skip_depth = 1
            return
        if tag in self.BLOCK_TAGS:
            self.parts.append("\n")

    def handle_startendtag(self, tag: str, attrs: list[tuple[str, str | None]]) -> None:
        if not self.skip_depth and tag.lower() in self.BLOCK_TAGS:
            self.parts.append("\n")

    def handle_endtag(self, tag: str) -> None:
        if self.skip_depth:
            self.skip_depth -= 1
            return
        if tag.lower() in self.BLOCK_TAGS:
            self.parts.append("\n")

    def handle_data(self, data: str) -> None:
        if not self.skip_depth and data:
            self.parts.append(data)


def html_to_text(raw_html: str) -> str:
    parser = EmailHTMLTextExtractor()
    try:
        parser.feed(raw_html)
        parser.close()
        text = "".join(parser.parts)
    except Exception:
        text = re.sub(r"(?is)<(script|style|blockquote).*?>.*?</\1>", " ", raw_html)
        text = re.sub(r"(?is)<br\s*/?>", "\n", text)
        text = re.sub(r"(?is)</p\s*>", "\n\n", text)
        text = re.sub(r"(?is)<[^>]+>", " ", text)
    text = html.unescape(text)
    text = re.sub(r"[ \t]+", " ", text)
    text = re.sub(r"\n[ \t]+", "\n", text)
    text = re.sub(r"\n{3,}", "\n\n", text)
    return text.strip()


def part_body_data(
    part: dict[str, Any],
    service: Any | None = None,
    message_id: str = "",
) -> str:
    body = part.get("body") or {}
    data = str(body.get("data") or "")
    if data:
        return data
    attachment_id = str(body.get("attachmentId") or "")
    if not (attachment_id and service is not None and message_id):
        return ""
    try:
        attachment = (
            service.users()
            .messages()
            .attachments()
            .get(userId="me", messageId=message_id, id=attachment_id)
            .execute()
        )
    except Exception:
        return ""
    return str(attachment.get("data") or "")


def payload_text(
    payload: dict[str, Any],
    service: Any | None = None,
    message_id: str = "",
) -> str:
    plain_parts: list[str] = []
    html_parts: list[str] = []

    def walk(part: dict[str, Any]) -> None:
        mime = part.get("mimeType", "")
        data = part_body_data(part, service, message_id)
        if mime == "text/plain" and data:
            plain_parts.append(decode_body_data(data))
        elif mime == "text/html" and data:
            html_parts.append(html_to_text(decode_body_data(data)))
        for child in part.get("parts") or []:
            walk(child)

    walk(payload)
    plain_text = clean_email_body("\n\n".join(part.strip() for part in plain_parts if part.strip()))
    if plain_text:
        return plain_text
    return clean_email_body("\n\n".join(part.strip() for part in html_parts if part.strip()))


def raw_message_text(service: Any, message_id: str) -> str:
    """Extract text from the RFC 822 source when Gmail's payload has no text part.

    Some mail clients produce reply MIME structures that Gmail exposes as an
    attachment-like part in ``format=full``. The raw representation retains
    the original MIME tree, which the standard library can decode reliably.
    """
    if not message_id:
        return ""
    try:
        raw = (
            service.users()
            .messages()
            .get(userId="me", id=message_id, format="raw")
            .execute()
            .get("raw", "")
        )
        if not raw:
            return ""
        message = BytesParser(policy=policy.default).parsebytes(
            base64.urlsafe_b64decode((raw + "=" * (-len(raw) % 4)).encode("utf-8"))
        )
    except Exception:
        return ""

    plain_parts: list[str] = []
    html_parts: list[str] = []
    for part in message.walk():
        if part.is_multipart() or part.get_content_disposition() == "attachment":
            continue
        content_type = part.get_content_type()
        if content_type not in {"text/plain", "text/html"}:
            continue
        try:
            content = part.get_content()
        except Exception:
            continue
        if not isinstance(content, str) or not content.strip():
            continue
        if content_type == "text/plain":
            plain_parts.append(content)
        else:
            html_parts.append(html_to_text(content))
    text = "\n\n".join(part.strip() for part in plain_parts if part.strip())
    if not text:
        text = "\n\n".join(part.strip() for part in html_parts if part.strip())
    return clean_email_body(text)


def is_reply_header_start(lines: list[str], index: int) -> bool:
    """Detect Outlook-style quoted header blocks without trimming normal prose."""
    stripped = lines[index].strip()
    if not re.match(r"(?i)^(?:From|发件人|寄件者)\s*[:：]", stripped):
        return False
    lookahead = [line.strip() for line in lines[index + 1 : index + 7] if line.strip()]
    header_hits = sum(
        1
        for line in lookahead
        if re.match(
            r"(?i)^(?:Sent|Date|To|Cc|Subject|发送时间|日期|收件人|抄送|主题|寄件日期|收件者)\s*[:：]",
            line,
        )
    )
    return header_hits >= 2


def strip_email_history(lines: list[str]) -> str:
    kept: list[str] = []
    for index, line in enumerate(lines):
        stripped = line.strip()
        if stripped.startswith(">"):
            continue
        wrapped_reply_header = " ".join(
            candidate.strip() for candidate in lines[index : index + 3] if candidate.strip()
        )
        if re.match(r"(?i)^On .+wrote\s*:$", wrapped_reply_header):
            break
        if re.match(r"(?i)^On .+(?:wrote\s*:|via .+<\s*)$", stripped):
            break
        if re.match(r"^在.+写道\s*[:：]$", stripped):
            break
        if kept and re.match(
            r"(?i)^(?:-{2,}\s*(?:Original Message|Forwarded message)\s*-{2,}|_{5,}|-{5,})$",
            stripped,
        ):
            break
        if kept and is_reply_header_start(lines, index):
            break
        kept.append(line.rstrip())
    cleaned = "\n".join(kept).strip()
    cleaned = re.sub(r"\n{4,}", "\n\n\n", cleaned)
    return cleaned


def clean_email_body(text: str) -> str:
    normalized = text.replace("\r\n", "\n").replace("\r", "\n")
    lines = normalized.split("\n")
    cleaned = strip_email_history(lines)
    if cleaned:
        return cleaned

    meaningful = [line for line in lines if line.strip()]
    quoted = [line for line in meaningful if line.lstrip().startswith(">")]
    if meaningful and len(quoted) >= max(1, int(len(meaningful) * 0.8)):
        dequoted = [re.sub(r"^\s*>\s?", "", line, count=1) for line in lines]
        return strip_email_history(dequoted)
    return ""


def format_address(value: str) -> str:
    name, addr = email.utils.parseaddr(value or "")
    if name and addr:
        return f"{name} <{addr}>"
    return addr or value or ""


def message_to_item(message: dict[str, Any], service: Any | None = None) -> dict[str, Any]:
    headers = header_map(message)
    internal_ms = int(message.get("internalDate") or 0)
    date = headers.get("date") or ""
    if not date and internal_ms:
        date = dt.datetime.fromtimestamp(internal_ms / 1000, dt.timezone.utc).isoformat()
    message_id = str(message.get("id") or "")
    body = payload_text(message.get("payload") or {}, service, message_id)
    if not body and service is not None:
        body = raw_message_text(service, message_id)
    return {
        "id": message.get("id", ""),
        "date": date,
        "internal_ms": internal_ms,
        "from": format_address(headers.get("from", "")),
        "to": format_address(headers.get("to", "")),
        "cc": format_address(headers.get("cc", "")),
        "subject": headers.get("subject", ""),
        "body": body,
    }


def record_contact_and_domain(record_fields: dict[str, Any]) -> tuple[str, str, str]:
    contact = extract_text(record_fields.get(FIELD_CONTACT))
    domain_value = extract_text(record_fields.get(FIELD_DOMAIN)).strip()
    email_match = re.search(r"[\w.+-]+@[\w.-]+\.[A-Za-z]{2,}", contact)
    domain_match = re.search(
        r"(?:https?://)?(?:www\.)?([A-Za-z0-9.-]+\.[A-Za-z]{2,})",
        domain_value,
    )
    email_addr = email_match.group(0) if email_match else ""
    domain = domain_match.group(1).lower() if domain_match else domain_value.split("/")[0].strip()
    return contact, email_addr, domain


def build_gmail_queries(record_fields: dict[str, Any], args: argparse.Namespace) -> list[str]:
    if args.gmail_query:
        return [args.gmail_query]
    contact, email_addr, domain = record_contact_and_domain(record_fields)
    freshness = f"newer_than:{args.newer_than}" if args.newer_than else ""
    address_term = f"(from:{email_addr} OR to:{email_addr})" if email_addr else ""
    domain_term = f'("{domain}" OR from:{domain} OR to:{domain})' if domain else ""
    contact_term = f'"{contact}"' if contact and not email_addr else ""
    candidates = [
        " ".join(term for term in (address_term or contact_term, domain_term, freshness) if term),
        " ".join(term for term in (address_term or contact_term, freshness) if term),
        " ".join(term for term in (domain_term, freshness) if term),
        " ".join(term for term in ((f'"{domain}"' if domain else ""), freshness) if term),
    ]
    queries: list[str] = []
    for query in candidates:
        query = query.strip()
        if query and query not in queries:
            queries.append(query)
    return queries


def build_gmail_query(record_fields: dict[str, Any], args: argparse.Namespace) -> str:
    queries = build_gmail_queries(record_fields, args)
    return queries[0] if queries else ""


def find_best_thread(service: Any, query: str, max_threads: int) -> dict[str, Any] | None:
    data = (
        service.users()
        .threads()
        .list(userId="me", q=query, maxResults=max_threads)
        .execute()
    )
    candidates = data.get("threads") or []
    if not candidates:
        return None
    threads = []
    for candidate in candidates:
        thread = (
            service.users()
            .threads()
            .get(userId="me", id=candidate["id"], format="full")
            .execute()
        )
        messages = [message_to_item(msg, service) for msg in thread.get("messages") or []]
        messages.sort(key=lambda item: item.get("internal_ms", 0))
        latest = max((msg["internal_ms"] for msg in messages), default=0)
        threads.append({"id": thread.get("id", candidate["id"]), "messages": messages, "latest": latest})
    threads.sort(key=lambda item: item["latest"], reverse=True)
    return threads[0]


def find_thread_with_fallbacks(
    service: Any,
    queries: list[str],
    max_threads: int,
) -> tuple[dict[str, Any] | None, str, list[str]]:
    tried: list[str] = []
    for query in queries:
        tried.append(query)
        thread = find_best_thread(service, query, max_threads)
        if thread:
            thread["matched_query"] = query
            thread["queries_tried"] = list(tried)
            return thread, query, tried
    return None, "", tried


def is_our_address(value: str) -> bool:
    _, addr = email.utils.parseaddr(value or "")
    lowered = addr.lower()
    return any(lowered.endswith(f"@{domain}") for domain in OUR_EMAIL_DOMAINS)


def sent_messages(messages: list[dict[str, Any]]) -> list[dict[str, Any]]:
    return [item for item in messages if is_our_address(item.get("from", ""))]


def incoming_messages(messages: list[dict[str, Any]]) -> list[dict[str, Any]]:
    return [item for item in messages if not is_our_address(item.get("from", ""))]


def body_excerpt(text: str, limit: int = 1200) -> str:
    text = re.sub(r"\s+", " ", (text or "").strip())
    if len(text) <= limit:
        return text
    return text[:limit].rstrip() + "..."


def detect_partner_request(messages: list[dict[str, Any]]) -> str:
    incoming_text = " ".join(item.get("body", "") for item in incoming_messages(messages)).lower()
    if any(term in incoming_text for term in ("guest post", "write a blog", "blog post", "publish", "contribute")):
        return "Partner asks about blog placement / guest post / publishing on our blog."
    if any(term in incoming_text for term in ("link exchange", "backlink", "reciprocal", "exchange links")):
        return "Partner is discussing backlink / reciprocal link exchange."
    if any(term in incoming_text for term in ("which page", "candidate", "url", "article", "anchor")):
        return "Partner is asking for placement details, candidate URLs, or anchor text."
    return "General ongoing backlink exchange discussion."


def latest_partner_message(messages: list[dict[str, Any]]) -> dict[str, Any] | None:
    for item in reversed(messages):
        if not is_our_address(item.get("from", "")):
            return item
    return None


