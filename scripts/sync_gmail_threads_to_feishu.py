def chunk_text(text: str, limit: int = 1800) -> list[str]:
    text = text.strip()
    if len(text) <= limit:
        return [text] if text else []
    chunks: list[str] = []
    current = ""
    for paragraph in re.split(r"(\n+)", text):
        if len(current) + len(paragraph) <= limit:
            current += paragraph
            continue
        if current.strip():
            chunks.append(current.strip())
            current = ""
        while len(paragraph) > limit:
            chunks.append(paragraph[:limit].strip())
            paragraph = paragraph[limit:]
        current = paragraph
    if current.strip():
        chunks.append(current.strip())
    return chunks


def markdown_to_blocks(markdown: str) -> list[dict[str, Any]]:
    blocks: list[dict[str, Any]] = []
    pending: list[str] = []

    def flush() -> None:
        if not pending:
            return
        paragraph = "\n".join(pending).strip()
        pending.clear()
        for chunk in chunk_text(paragraph):
            blocks.append(text_block(chunk))

    for raw in markdown.splitlines():
        line = raw.rstrip()
        stripped = line.strip()
        if not stripped:
            flush()
            continue
        if stripped.startswith("### "):
            flush()
            blocks.append(text_block(stripped[4:].strip(), 5))
        elif stripped.startswith("## "):
            flush()
            blocks.append(text_block(stripped[3:].strip(), 4))
        elif stripped.startswith("# "):
            flush()
            blocks.append(text_block(stripped[2:].strip(), 3))
        elif stripped.startswith(("- ", "* ")):
            flush()
            blocks.append(text_block("• " + stripped[2:].strip()))
        else:
            pending.append(stripped)
    flush()
    return blocks


