def load_json(path: Path) -> dict[str, Any]:
    with path.open(encoding="utf-8") as f:
        return json.load(f)


def load_feishu_config(args: argparse.Namespace) -> dict[str, Any]:
    candidates: list[Path] = []
    if args.feishu_config:
        candidates.append(Path(args.feishu_config).expanduser())
    if os.environ.get("FEISHU_CONFIG_PATH"):
        candidates.append(Path(os.environ["FEISHU_CONFIG_PATH"]).expanduser())
    candidates.extend(
        [
            Path("config/feishu-config.json"),
            Path.home() / ".codex" / "feishu_config.json",
            Path("../zilliz-medium-pipeline/config/feishu-config.json"),
            Path("../X Automation/feishu-config.json"),
        ]
    )
    existing = [path for path in candidates if path and path.exists()]
    if not existing:
        raise SystemExit(
            "Missing Feishu config. Set FEISHU_CONFIG_PATH or pass --feishu-config."
        )
    required = ("app_id", "app_secret", "bitable_app_token")
    invalid: list[str] = []
    for path in existing:
        config = load_json(path)
        missing = [key for key in required if not config.get(key)]
        if missing:
            invalid.append(f"{path} (missing {', '.join(missing)})")
            continue
        config["_path"] = str(path)
        return config
    raise SystemExit("No usable Feishu config found: " + "; ".join(invalid))


def feishu_token(config: dict[str, Any]) -> str:
    data = requests.post(
        f"{FEISHU_BASE}/auth/v3/tenant_access_token/internal",
        json={"app_id": config["app_id"], "app_secret": config["app_secret"]},
        timeout=20,
    ).json()
    if data.get("code") != 0:
        raise RuntimeError(f"Failed to get Feishu token: {data}")
    return data["tenant_access_token"]


def feishu_headers(token: str) -> dict[str, str]:
    return {"Authorization": f"Bearer {token}", "Content-Type": "application/json"}


def extract_text(value: Any) -> str:
    if value is None:
        return ""
    if isinstance(value, str):
        return value.strip()
    if isinstance(value, (int, float)):
        return str(value)
    if isinstance(value, list):
        parts = []
        for item in value:
            if isinstance(item, dict):
                parts.append(
                    str(
                        item.get("text")
                        or item.get("name")
                        or item.get("link")
                        or item.get("url")
                        or ""
                    )
                )
            else:
                parts.append(str(item))
        return " ".join(part for part in parts if part).strip()
    if isinstance(value, dict):
        return str(
            value.get("text")
            or value.get("name")
            or value.get("link")
            or value.get("url")
            or json.dumps(value, ensure_ascii=False)
        ).strip()
    return str(value).strip()


def extract_url(value: Any) -> str:
    if value is None:
        return ""
    if isinstance(value, str):
        markdown_match = re.search(r"\[[^\]]*\]\((https?://[^)\s]+)\)", value)
        if markdown_match:
            return markdown_match.group(1)
        url_match = re.search(r"https?://[^\s)]+", value)
        return url_match.group(0) if url_match else ""
    if isinstance(value, list):
        for item in value:
            found = extract_url(item)
            if found:
                return found
        return ""
    if isinstance(value, dict):
        for key in ("link", "url", "href", "text"):
            found = extract_url(value.get(key))
            if found:
                return found
        return ""
    return ""


def list_records(
    token: str,
    app_token: str,
    table_id: str,
    view_id: str = "",
    page_size: int = 500,
) -> list[dict[str, Any]]:
    records: list[dict[str, Any]] = []
    page_token = ""
    while True:
        url = (
            f"{FEISHU_BASE}/bitable/v1/apps/{app_token}/tables/{table_id}"
            f"/records?page_size={page_size}&automatic_fields=false"
            f"&text_field_as_array=true"
        )
        if view_id:
            url += f"&view_id={view_id}"
        if page_token:
            url += f"&page_token={page_token}"
        data = requests.get(url, headers=feishu_headers(token), timeout=30).json()
        if data.get("code") != 0:
            raise RuntimeError(f"Failed to list records: {data}")
        payload = data.get("data") or {}
        records.extend(payload.get("items", []))
        if not payload.get("has_more"):
            break
        page_token = payload.get("page_token") or ""
    return records


